// Специфікація PdfDocument (T-181): звіт має бути валідним PDF — заголовок,
// xref, текстовий потік — і віддаватись у Writable через pipe/end.
import { Writable } from 'node:stream';
import { PdfDocument } from './pdf-document';

function collector(): { chunks: Buffer[]; stream: Writable } {
  const chunks: Buffer[] = [];
  const stream = new Writable({
    write(chunk, _encoding, callback) {
      chunks.push(Buffer.from(chunk));
      callback();
    },
  });
  return { chunks, stream };
}

describe('PdfDocument', () => {
  it('produces a valid PDF header and trailer', () => {
    const doc = new PdfDocument({ margin: 40, size: 'A4' });
    doc.fontSize(18).text('Waitlist Analytics Report');
    const pdf = doc.toBuffer().toString('latin1');

    expect(pdf.startsWith('%PDF-1.4')).toBe(true);
    expect(pdf).toContain('/Type /Catalog');
    expect(pdf).toContain('xref');
    expect(pdf.trimEnd().endsWith('%%EOF')).toBe(true);
  });

  it('writes report text into the content stream', () => {
    const doc = new PdfDocument();
    doc.fontSize(12).text('Promoted to Booked: 42');
    const pdf = doc.toBuffer().toString('latin1');

    expect(pdf).toContain('(Promoted to Booked: 42) Tj');
  });

  it('escapes parentheses so the text operator stays balanced', () => {
    const doc = new PdfDocument();
    doc.text('rate (31.5%)');
    expect(doc.toBuffer().toString('latin1')).toContain('(rate \\(31.5%\\)) Tj');
  });

  it('streams the finished document through pipe/end', async () => {
    const { chunks, stream } = collector();
    const doc = new PdfDocument();
    doc.pipe(stream);
    doc.fontSize(11).text('Generated by Barbershop Platform');

    await new Promise<void>((resolve) => {
      stream.on('finish', resolve);
      doc.end();
    });

    const written = Buffer.concat(chunks).toString('latin1');
    expect(written.startsWith('%PDF-1.4')).toBe(true);
    expect(written).toContain('(Generated by Barbershop Platform) Tj');
  });

  it('centres and draws rules without breaking the stream', () => {
    const doc = new PdfDocument();
    doc.fontSize(20).text('Centered', { align: 'center' });
    doc.moveTo(50, doc.page.height - 50).lineTo(doc.page.width - 50, doc.page.height - 50).stroke();
    const pdf = doc.toBuffer().toString('latin1');

    expect(pdf).toContain('(Centered) Tj');
    expect(pdf).toMatch(/ l S/);
  });
});
