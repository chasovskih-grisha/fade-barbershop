// T-4616b: текст позначеного дня. Один візит, кілька візитів і порожній день
// звучать по-різному, і жоден варіант не називає причини («лікар»).
import { countVisits } from '../../../lib/barber-unavailability';

export function markedDayText(conflicts: number): string {
  if (conflicts <= 0) return 'Цей день закритий. Візитів, які чекають рішення, немає.';
  if (conflicts === 1) {
    return 'Цей день закритий. 1 візит чекає рішення засновника — клієнта переносить адміністратор.';
  }
  return `Цей день закритий. ${countVisits(conflicts)} чекають рішення засновника — клієнтів переносить адміністратор.`;
}
